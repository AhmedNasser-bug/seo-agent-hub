-- ==============================================================================
-- Declarative SQLite State Store Schema for seo-agent-hub
-- Compliant with Microsoft WAF Protocols (SEC-02, SEC-04, REL-05, REL-06)
-- ==============================================================================

PRAGMA foreign_keys = ON;
PRAGMA journal_mode = WAL;
PRAGMA synchronous = NORMAL;

-- Resource Locks Table (SEC-04 Delete Protection)
CREATE TABLE IF NOT EXISTS resource_locks (
    lock_name TEXT PRIMARY KEY,
    locked_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    locked_by TEXT NOT NULL
);

-- Research Insights from Firecrawl MCP and arXiv MCP
CREATE TABLE IF NOT EXISTS research_insights (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    source TEXT NOT NULL,                     -- e.g. "firecrawl:competitor" | "arxiv:paperqa"
    title TEXT NOT NULL,
    target_cohort TEXT NOT NULL,              -- e.g. "18-24", "25-34", "35-44", "45-54", "55-64", "65+", "all"
    raw_data_json TEXT NOT NULL,              -- Telemetry & source citations
    hypothesis TEXT NOT NULL,                 -- Conversion hypothesis for page generation
    priority INTEGER DEFAULT 1,               -- 1 (Critical) to 5 (Low)
    status TEXT DEFAULT 'PENDING_GENERATION', -- 'PENDING_GENERATION' | 'GENERATED' | 'REJECTED'
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- Pages & Variants Generated by Jules + Stitch MCP
CREATE TABLE IF NOT EXISTS generated_pages (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    insight_id INTEGER REFERENCES research_insights(id),
    page_type TEXT NOT NULL,                  -- 'landing_variant' | 'blog_post' | 'standalone_page'
    route_path TEXT NOT NULL,                 -- e.g. "/" | "/blog/dialysis-ai-safety-2026"
    cohort TEXT NOT NULL,                     -- "18-24" (primary) | "25-34" | "35-44" | "45-54" | "55-64" | "65+"
    title TEXT NOT NULL,
    target_selector TEXT DEFAULT 'body',      -- For in-place DOM hydration or full page replacement
    generated_html TEXT NOT NULL,             -- Full HTML / DOM fragment returned by Stitch MCP
    stitch_project_id TEXT,                   -- Google Stitch Project ID
    stitch_screen_id TEXT,                    -- Google Stitch Screen ID
    validation_status TEXT DEFAULT 'PENDING', -- 'PENDING' | 'PASSED' | 'FAILED'
    openseo_score INTEGER DEFAULT 0,          -- OpenSEO audit score (0-100)
    unlighthouse_score INTEGER DEFAULT 0,     -- Unlighthouse performance score (0-100)
    approval_status TEXT DEFAULT 'DRAFT',     -- 'DRAFT' | 'APPROVED' | 'ACTIVE_TEST' | 'ROLLED_BACK' | 'PROMOTED_WINNER'
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- GrowthBook A/B Experiments Matrix (6 Cohorts)
CREATE TABLE IF NOT EXISTS ab_experiments (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    experiment_key TEXT UNIQUE NOT NULL,      -- e.g. "exp_hero_cohort_18_24_medgemma"
    page_id INTEGER REFERENCES generated_pages(id),
    cohort TEXT NOT NULL,                     -- "18-24" | "25-34" | "35-44" | "45-54" | "55-64" | "65+"
    traffic_pct INTEGER DEFAULT 50,           -- 50% Control vs 50% Stitch Variant
    control_impressions INTEGER DEFAULT 0,
    control_conversions INTEGER DEFAULT 0,
    variant_impressions INTEGER DEFAULT 0,
    variant_conversions INTEGER DEFAULT 0,
    status TEXT DEFAULT 'ACTIVE',             -- 'ACTIVE' | 'PAUSED' | 'CONCLUDED'
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- Daily Action Items (Prioritized for User & Spark Dispatch)
CREATE TABLE IF NOT EXISTS action_items (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    priority TEXT NOT NULL,                   -- 'CRITICAL' | 'HIGH' | 'MEDIUM' | 'LOW'
    category TEXT NOT NULL,                   -- 'SEO' | 'AEO' | 'PAGE_GENERATION' | 'CONVERSION'
    title TEXT NOT NULL,
    rationale TEXT NOT NULL,
    source_agent TEXT NOT NULL,               -- 'research' | 'validation' | 'orchestrator' | 'appearance'
    status TEXT DEFAULT 'TODO',               -- 'TODO' | 'IN_PROGRESS' | 'DONE'
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- Captured Leads & Contact Records
CREATE TABLE IF NOT EXISTS leads (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL,
    institution TEXT NOT NULL,
    email TEXT NOT NULL,
    inquiry_type TEXT NOT NULL,
    cohort TEXT DEFAULT '18-24',
    source TEXT DEFAULT 'landing_page_partner_form',
    dispatched_by_spark INTEGER DEFAULT 0,    -- 0: pending, 1: emailed to user
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- Real-time Agent Collaboration Stream
CREATE TABLE IF NOT EXISTS agent_messages (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    sender TEXT NOT NULL,                     -- 'user' | 'jules-orchestrator' | 'research-agent' | 'stitch-mcp' | 'validation-gate' | 'spark-agent'
    recipient TEXT NOT NULL,
    content TEXT NOT NULL,
    metadata_json TEXT DEFAULT '{}',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- Spark Daily Digest Messaging Resiliency (REL-05 PeekLock & Dead-Letter Queue)
CREATE TABLE IF NOT EXISTS spark_digests (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    idempotency_key TEXT UNIQUE NOT NULL,     -- e.g. "spark_digest_2026-11-09"
    recipient_email TEXT NOT NULL,
    lock_status TEXT DEFAULT 'UNLOCKED',      -- 'UNLOCKED' | 'PEEK_LOCKED' | 'COMPLETED' | 'DEAD_LETTER'
    retry_count INTEGER DEFAULT 0,
    is_transient INTEGER DEFAULT 1,
    payload_json TEXT NOT NULL,
    dispatched_at DATETIME
);

-- SEC-04 Resource Locks Delete Protection Triggers
CREATE TRIGGER IF NOT EXISTS trg_prevent_delete_leads
BEFORE DELETE ON leads
BEGIN
    SELECT CASE
        WHEN (SELECT COUNT(*) FROM resource_locks WHERE lock_name = 'CanNotDelete') > 0
        THEN RAISE(ABORT, 'WAF SEC-04 Violation: leads table has an active CanNotDelete resource lock')
    END;
END;

CREATE TRIGGER IF NOT EXISTS trg_prevent_delete_generated_pages
BEFORE DELETE ON generated_pages
BEGIN
    SELECT CASE
        WHEN (SELECT COUNT(*) FROM resource_locks WHERE lock_name = 'CanNotDelete') > 0
        THEN RAISE(ABORT, 'WAF SEC-04 Violation: generated_pages table has an active CanNotDelete resource lock')
    END;
END;

CREATE TRIGGER IF NOT EXISTS trg_prevent_delete_action_items
BEFORE DELETE ON action_items
BEGIN
    SELECT CASE
        WHEN (SELECT COUNT(*) FROM resource_locks WHERE lock_name = 'CanNotDelete') > 0
        THEN RAISE(ABORT, 'WAF SEC-04 Violation: action_items table has an active CanNotDelete resource lock')
    END;
END;

-- Default Resource Lock (SEC-04)
INSERT OR IGNORE INTO resource_locks (lock_name, locked_by) 
VALUES ('CanNotDelete', 'system:antigravity:waf_protocol');
